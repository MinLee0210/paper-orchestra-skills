#!/usr/bin/env python3
"""Scaffold a systems-venue template into the paper-orchestra template contract.

The bundled systems templates ship as `main.tex` + `references.bib` + style
files. The paper-orchestra pipeline (paper-inputs, pipeline_status.py) expects
`latex_template/template.tex`, `guidelines.md`, and `references.bib`. This
script copies a venue directory, renames main.tex to template.tex, and writes
guidelines.md from the venue's own header comment, quoted verbatim so no page
limit is paraphrased.

Example:
    python init_systems_template.py --list
    python init_systems_template.py --venue osdi2026 --out paper_project/latex_template
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

TEMPLATES = Path(__file__).resolve().parent.parent / "templates"


def header_comment(tex: str) -> list[str]:
    """Leading block of % comment lines, stripped of the comment markers."""
    lines: list[str] = []
    for raw in tex.splitlines():
        stripped = raw.strip()
        if not stripped.startswith("%"):
            if lines or stripped:
                break
            continue
        text = stripped.lstrip("%").strip().rstrip("%").strip()
        if set(text) <= {"%", " "}:  # banner lines such as %%%%%%%%
            continue
        lines.append(text)
    return lines


def guidelines(venue: str, header: list[str]) -> str:
    body = "\n".join(f"> {line}" if line else ">" for line in header)
    return (
        f"# {venue} guidelines\n\n"
        "Generated by `init_systems_template.py` from the header comment of the bundled template, "
        "quoted verbatim. Venue rules change every year: **verify page limit, anonymity, and track "
        "rules against the current call for papers before submission**, and edit this file if they differ.\n\n"
        "## Rules quoted from the template header\n\n"
        f"{body}\n\n"
        "## Pipeline notes\n\n"
        "- The page limit counts the main text up to the start of References; references are not counted.\n"
        "- The template ships as a full sample paper. Keep its `\\documentclass`, packages, and style file; "
        "section bodies may be replaced.\n"
        "- Structure guidance (page budget per section, paragraph blueprints) lives in the "
        "`research-systems-paper-writing` skill.\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--venue", help="Template key, e.g. osdi2026")
    parser.add_argument("--out", help="Destination directory (becomes latex_template/)")
    parser.add_argument("--force", action="store_true", help="Overwrite files in a non-empty directory")
    parser.add_argument("--list", action="store_true", help="List bundled systems venues and exit")
    args = parser.parse_args()

    venues = sorted(p.name for p in TEMPLATES.iterdir() if (p / "main.tex").exists()) if TEMPLATES.is_dir() else []
    if args.list:
        print("\n".join(venues))
        return 0
    if not args.venue or not args.out:
        parser.error("--venue and --out are required unless --list is used")
    if args.venue not in venues:
        print(f"error: unknown venue '{args.venue}'. Available: {', '.join(venues)}", file=sys.stderr)
        return 2

    source = TEMPLATES / args.venue
    dest = Path(args.out).expanduser().resolve()
    if dest.exists() and any(dest.iterdir()) and not args.force:
        print(f"error: {dest} is not empty (use --force to overwrite)", file=sys.stderr)
        return 2
    dest.mkdir(parents=True, exist_ok=True)

    for item in sorted(source.iterdir()):
        target = dest / ("template.tex" if item.name == "main.tex" else item.name)
        if item.is_dir():
            shutil.copytree(item, target, dirs_exist_ok=True)
        else:
            shutil.copy2(item, target)

    tex = (dest / "template.tex").read_text(encoding="utf-8", errors="replace")
    (dest / "guidelines.md").write_text(guidelines(args.venue, header_comment(tex)), encoding="utf-8")
    if not (dest / "references.bib").exists():
        (dest / "references.bib").write_text("", encoding="utf-8")

    print(f"Scaffolded {args.venue} -> {dest}")
    for item in sorted(dest.iterdir()):
        print(f"  {item.name}")
    print("Template contract satisfied. Verify guidelines.md against the current call for papers.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
